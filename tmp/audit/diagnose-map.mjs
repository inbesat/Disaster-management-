import { chromium } from '@playwright/test';
const browser=await chromium.launch({headless:true});
const base='http://localhost:3100';
const context=await browser.newContext({viewport:{width:1366,height:850}});
await context.addCookies([{name:'role',value:'district_admin',url:base}]);
const page=await context.newPage();
page.on('pageerror',e=>console.log('PAGE ERROR',e.message.slice(0,300)));
page.on('console',m=>{if(m.type()==='error') console.log('CONSOLE ERROR',m.text().slice(0,250))});
await page.goto(base+'/map',{waitUntil:'domcontentloaded',timeout:120000});
const input=page.getByRole('searchbox',{name:'Search places on the map'});
await input.waitFor({timeout:90000});
console.log('search before',await input.count());
await input.fill('Patna, India');
await page.getByRole('button',{name:'Find',exact:true}).click();
await page.getByRole('list',{name:'Place search results'}).waitFor({timeout:30000});
console.log('results',await page.getByRole('list',{name:'Place search results'}).innerText());
await page.getByRole('list',{name:'Place search results'}).getByRole('button').first().click();
await page.waitForTimeout(2500);
console.log('search card',await input.locator('..').locator('..').innerText());
console.log('alerts',await page.getByRole('alert').allInnerTexts());
console.log('header',await page.locator('h1').first().innerText());
await page.screenshot({path:'tmp/audit/map-search.png'});
await browser.close();
